    private void carregarTabela() {

        DefaultTableModel modelo
                = (DefaultTableModel) tableAdministradores.getModel();

        modelo.setRowCount(0);

        List<Administrador> lista
                = administradorDAO.listar();

        for (Administrador administrador
                : lista) {

            modelo.addRow(new Object[]{
                administrador.getId_adm(),
                administrador.getNome(),
                administrador.getEmail(),
                MascaraUtil.formatarTelefone(
                administrador.getTelefone()
                ),
                administrador.isStatus()
                ? "ATIVO"
                : "INATIVO"
            });
        }
    }

