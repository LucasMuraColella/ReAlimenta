    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (id_admin_selecionado == 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um administrador."
            );

            return;
        }

        String nome
                = txtNome.getText().trim();

        String email
                = txtEmail.getText().trim();

        String senha
                = new String(
                        txtSenha.getPassword()
                );

        String telefone
                = MascaraUtil.somenteNumeros(
                        txtTelefone.getText()
                );

        if (nome.isEmpty()
                || email.isEmpty()
                || senha.isEmpty()
                || telefone.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Preencha todos os campos."
            );

            return;
        }

        Administrador administrador
                = new Administrador();

        administrador.setId_adm(
                id_admin_selecionado
        );

        administrador.setNome(nome);
        administrador.setEmail(email);
        administrador.setSenha(senha);
        administrador.setTelefone(telefone);

        administrador.setStatus(
                "ATIVO".equals(
                        cbStatus
                                .getSelectedItem()
                                .toString()
                )
        );

        administradorDAO.atualizar(
                administrador
        );

        JOptionPane.showMessageDialog(
                this,
                "Administrador alterado com sucesso!"
        );

        limparCampos();
        carregarTabela();
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome
                = txtNome.getText().trim();

        String email
                = txtEmail.getText().trim();

        String senha
                = new String(
                        txtSenha.getPassword()
                );

        String telefone
                = MascaraUtil.somenteNumeros(
                        txtTelefone.getText()
                );

        if (nome.isEmpty()
                || email.isEmpty()
                || senha.isEmpty()
                || telefone.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Preencha todos os campos."
            );

            return;
        }

        if (!ValidadorUtil.emailValido(email)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Informe um e-mail válido."
            );

            return;
        }

        if (telefone.length() < 10) {

            JOptionPane.showMessageDialog(
                    this,
                    "Informe um telefone válido."
            );

            return;
        }

        if (senha.length() < 6) {

            JOptionPane.showMessageDialog(
                    this,
                    "A senha deve possuir pelo menos 6 caracteres."
            );

            return;
        }

        Administrador administrador
                = new Administrador();

        administrador.setNome(nome);
        administrador.setEmail(email);
        administrador.setSenha(
                SenhaUtil.gerarHash(senha)
        );
        administrador.setTelefone(telefone);

        administrador.setStatus(
                "ATIVO".equals(
                        cbStatus
                                .getSelectedItem()
                                .toString()
                )
        );

        administradorDAO.cadastrar(
                administrador
        );

        JOptionPane.showMessageDialog(
                this,
                "Administrador cadastrado com sucesso!"
        );

        limparCampos();
        carregarTabela();
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void tableAdministradoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableAdministradoresMouseClicked
        int linha
                = tableAdministradores.getSelectedRow();

        if (linha < 0) {
            return;
        }

        id_admin_selecionado
                = Integer.parseInt(
                        tableAdministradores
                                .getValueAt(linha, 0)
                                .toString()
                );

        Administrador administrador
                = administradorDAO.buscarPorId(
                        id_admin_selecionado
                );

        if (administrador == null) {
            return;
        }

        txtNome.setText(
                administrador.getNome()
        );

        txtEmail.setText(
                administrador.getEmail()
        );

        txtSenha.setText("");

        txtTelefone.setText(
                MascaraUtil.formatarTelefone(
                        administrador.getTelefone()
                )
        );

        cbStatus.setSelectedItem(
                administrador.isStatus()
                ? "ATIVO"
                : "INATIVO"
        );
    }//GEN-LAST:event_tableAdministradoresMouseClicked

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (id_admin_selecionado == 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione um administrador."
            );

            return;
        }

        int resposta
                = JOptionPane.showConfirmDialog(
                        this,
                        "Deseja realmente excluir "
                        + "este administrador?",
                        "Confirmação",
                        JOptionPane.YES_NO_OPTION
                );

        if (resposta
                == JOptionPane.YES_OPTION) {

            administradorDAO.excluir(
                    id_admin_selecionado
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Administrador excluído com sucesso!"
            );

            limparCampos();
            carregarTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

