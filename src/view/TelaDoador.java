    private void carregarTabela() {

        DefaultTableModel modelo = (DefaultTableModel) tableDoadores.getModel();

        modelo.setRowCount(0);

        List<Doador> lista = doadorDAO.listar();

        for (Doador doador : lista) {

            modelo.addRow(new Object[]{
                doador.getId_doador(),
                doador.getNome(),
                MascaraUtil.formatarCpfCnpj(
                doador.getCpf_cnpj()
                ),
                MascaraUtil.formatarTelefone(
                doador.getTelefone()
                ),
                MascaraUtil.formatarCep(
                doador.getCep()
                ),
                doador.getRua(),
                doador.getNumero(),
                doador.getBairro()
            });

        }
    }

