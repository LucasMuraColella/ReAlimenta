    private void btnBuscarCepActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarCepActionPerformed
        String cep
                = MascaraUtil.somenteNumeros(
                        txtCep.getText()
                );

        if (cep.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Digite um CEP."
            );

            return;
        }

        try {

            CepResposta resposta
                    = ViaCepUtil.buscar(cep);

            if (resposta.isErro()) {

                JOptionPane.showMessageDialog(
                        this,
                        "CEP não encontrado."
                );

                return;
            }

            if (!"Santa Fé do Sul"
                    .equalsIgnoreCase(
                            resposta.getLocalidade()
                    )
                    || !"SP".equalsIgnoreCase(
                            resposta.getUf()
                    )) {

                JOptionPane.showMessageDialog(
                        this,
                        "O CEP deve pertencer a "
                        + "Santa Fé do Sul - SP."
                );

                return;
            }

            txtRua.setText(
                    resposta.getLogradouro()
            );

            txtBairro.setText(
                    resposta.getBairro()
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Endereço preenchido com sucesso!"
            );

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "CEP inválido. Digite 8 números."
            );

        } catch (IOException
                | InterruptedException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Não foi possível consultar o CEP."
            );
        }
    }//GEN-LAST:event_btnBuscarCepActionPerformed

    private void tableDoadoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableDoadoresMouseClicked
        int linha = tableDoadores.getSelectedRow();

        if (linha >= 0) {

            idDoadorSelecionado = Integer.parseInt(
                    tableDoadores.getValueAt(linha, 0).toString()
            );

            txtNome.setText(
                    tableDoadores
                            .getValueAt(linha, 1)
                            .toString()
            );

            txtCpfCnpj.setText(
                    MascaraUtil.formatarCpfCnpj(
                            tableDoadores
                                    .getValueAt(linha, 2)
                                    .toString()
                    )
            );

            txtTelefone.setText(
                    MascaraUtil.formatarTelefone(
                            tableDoadores
                                    .getValueAt(linha, 3)
                                    .toString()
                    )
            );

            txtCep.setText(
                    MascaraUtil.formatarCep(
                            tableDoadores
                                    .getValueAt(linha, 4)
                                    .toString()
                    )
            );

            txtRua.setText(
                    tableDoadores.getValueAt(linha, 5).toString()
            );

            txtNumero.setText(
                    tableDoadores.getValueAt(linha, 6).toString()
            );

            txtBairro.setText(
                    tableDoadores.getValueAt(linha, 7).toString()
            );
        }
    }//GEN-LAST:event_tableDoadoresMouseClicked

