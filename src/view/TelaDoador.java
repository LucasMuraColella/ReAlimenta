    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome = txtNome.getText().trim();
        String cpf_cnpj
                = MascaraUtil.somenteNumeros(
                        txtCpfCnpj.getText()
                );

        String telefone
                = MascaraUtil.somenteNumeros(
                        txtTelefone.getText()
                );

        String cep
                = MascaraUtil.somenteNumeros(
                        txtCep.getText()
                );
        String rua = txtRua.getText().trim();
        String numero = txtNumero.getText().trim();
        String bairro = txtBairro.getText().trim();

        if (nome.isEmpty()
                || cpf_cnpj.isEmpty()
                || telefone.isEmpty()
                || cep.isEmpty()
                || rua.isEmpty()
                || numero.isEmpty()
                || bairro.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Preencha todos os campos.");

            return;
        }

        if (cpf_cnpj.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Informe o CPF/CNPJ."
            );

            return;
        }

        if (cpf_cnpj.length() > 18) {

            JOptionPane.showMessageDialog(
                    this,
                    "O CPF/CNPJ deve possuir no máximo 18 caracteres."
            );

            return;
        }

        if (telefone.length() < 10) {

            JOptionPane.showMessageDialog(
                    this,
                    "Informe um telefone válido."
            );

            return;
        }

        Doador doador = new Doador();

        doador.setNome(nome);
        doador.setCpf_cnpj(cpf_cnpj);
        doador.setTelefone(telefone);
        doador.setCep(cep);
        doador.setRua(rua);
        doador.setNumero(numero);
        doador.setBairro(bairro);

        doadorDAO.cadastrar(doador);

        JOptionPane.showMessageDialog(this,
                "Doador cadastrado com sucesso!");

        limparCampos();
        carregarTabela();
    }//GEN-LAST:event_btnCadastrarActionPerformed

