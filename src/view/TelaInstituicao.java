    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (idInstituicaoSelecionada == 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma instituição na tabela."
            );

            return;
        }

        String nome
                = txtNome.getText().trim();

        String cnpj
                = MascaraUtil.somenteNumeros(
                        txtCnpj.getText()
                );

        String responsavel
                = txtResponsavel.getText().trim();

        String cep
                = MascaraUtil.somenteNumeros(
                        txtCep.getText()
                );

        String rua
                = txtRua.getText().trim();

        String numero
                = txtNumero.getText().trim();

        String bairro
                = txtBairro.getText().trim();

        if (nome.isEmpty()
                || cnpj.isEmpty()
                || responsavel.isEmpty()
                || cep.isEmpty()
                || rua.isEmpty()
                || numero.isEmpty()
                || bairro.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Preencha todos os campos."
            );

            return;
        }

        if (cnpj.length() != 14) {

            JOptionPane.showMessageDialog(
                    this,
                    "O CNPJ deve possuir 14 números."
            );

            return;
        }

        if (cep.length() != 8) {

            JOptionPane.showMessageDialog(
                    this,
                    "O CEP deve possuir 8 números."
            );

            return;
        }

        Instituicao instituicao
                = new Instituicao();

        instituicao.setId_instituicao(
                idInstituicaoSelecionada
        );

        instituicao.setNome(nome);

        instituicao.setCnpj(cnpj);

        instituicao.setResponsavel(
                responsavel
        );

        instituicao.setCep(cep);

        instituicao.setRua(rua);

        instituicao.setNumero(numero);

        instituicao.setBairro(bairro);

        instituicaoDAO.atualizar(
                instituicao
        );

        JOptionPane.showMessageDialog(
                this,
                "Instituição alterada com sucesso!"
        );

        limparCampos();

        carregarTabela();
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idInstituicaoSelecionada == 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma instituição na tabela."
            );

            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir esta instituição?",
                "Confirmação",
                JOptionPane.YES_NO_OPTION
        );

        if (resposta == JOptionPane.YES_OPTION) {

            boolean excluiu
                    = instituicaoDAO.excluir(
                            idInstituicaoSelecionada
                    );

            if (excluiu) {

                JOptionPane.showMessageDialog(
                        this,
                        "Instituição excluída com sucesso!",
                        "Sucesso",
                        JOptionPane.INFORMATION_MESSAGE
                );

                limparCampos();
                carregarTabela();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Não é possível excluir esta instituição.\n\n"
                        + "Ela possui solicitações cadastradas "
                        + "vinculadas a ela.\n"
                        + "Para preservar o histórico das solicitações, "
                        + "a instituição não pode ser excluída.",
                        "Instituição vinculada",
                        JOptionPane.WARNING_MESSAGE
                );
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

