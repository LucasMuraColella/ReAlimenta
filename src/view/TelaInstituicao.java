    private void btnBuscarCepActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarCepActionPerformed
        String cep
                = MascaraUtil.somenteNumeros(
                        txtCep.getText()
                );

        if (cep.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Digite um CEP."
            );

            return;
        }

        try {

            CepResposta resposta
                    = ViaCepUtil.buscar(cep);

            if (resposta.isErro()) {

                JOptionPane.showMessageDialog(
                        this,
                        "CEP não encontrado."
                );

                return;
            }

            if (!"Santa Fé do Sul"
                    .equalsIgnoreCase(
                            resposta.getLocalidade()
                    )
                    || !"SP".equalsIgnoreCase(
                            resposta.getUf()
                    )) {

                JOptionPane.showMessageDialog(
                        this,
                        "O CEP deve pertencer a "
                        + "Santa Fé do Sul - SP."
                );

                return;
            }

            txtRua.setText(
                    resposta.getLogradouro()
            );

            txtBairro.setText(
                    resposta.getBairro()
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Endereço preenchido com sucesso!"
            );

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "CEP inválido."
            );

        } catch (IOException
                | InterruptedException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Não foi possível consultar o CEP."
            );
        }
    }//GEN-LAST:event_btnBuscarCepActionPerformed

