    private void carregarTabela() {

        DefaultTableModel modelo
                = (DefaultTableModel) tableInstituicoes.getModel();

        modelo.setRowCount(0);

        List<Instituicao> lista = instituicaoDAO.listar();

        for (Instituicao instituicao : lista) {

            modelo.addRow(new Object[]{
                instituicao.getId_instituicao(),
                instituicao.getNome(),
                MascaraUtil.formatarCpfCnpj(
                instituicao.getCnpj()
                ),
                instituicao.getResponsavel(),
                MascaraUtil.formatarCep(
                instituicao.getCep()
                ),
                instituicao.getRua(),
                instituicao.getNumero(),
                instituicao.getBairro()
            });
        }
    }

