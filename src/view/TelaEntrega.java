    private void carregarItensDaSolicitacao(
            int fk_solicitacao) {

        DefaultTableModel modelo
                = (DefaultTableModel) tableItens.getModel();

        modelo.setRowCount(0);

        if (fk_solicitacao == 0) {
            return;
        }

        List<ItemSolicitacao> itens
                = itemSolicitacaoDAO
                        .listarPorSolicitacao(
                                fk_solicitacao
                        );

        List<Alimento> alimentos
                = alimentoDAO.listar();

        for (ItemSolicitacao item
                : itens) {

            String nome_alimento = "";
            String unidade_medida = "";

            for (Alimento alimento
                    : alimentos) {

                if (alimento.getId_alimento()
                        == item.getFk_alimento()) {

                    nome_alimento
                            = alimento.getNome();

                    unidade_medida
                            = alimento.getUnidade_medida();

                    break;
                }
            }

            modelo.addRow(new Object[]{
                nome_alimento,
                item.getQuantidade_solicitada(),
                unidade_medida
            });
        }
    }

    private void carregarSolicitacoes() {

        cbSolicitacao.removeAllItems();

        List<Integer> lista
                = entregaDAO.listarSolicitacoesDisponiveis();

        for (Integer id
                : lista) {

            cbSolicitacao.addItem(
                    "Solicitação #" + id
            );
        }
    }

    private int obterIdSolicitacaoSelecionada() {

        if (cbSolicitacao.getSelectedItem() == null) {
            return 0;
        }

        String texto
                = cbSolicitacao
                        .getSelectedItem()
                        .toString();

        return Integer.parseInt(
                texto.replace(
                        "Solicitação #",
                        ""
                )
        );
    }

    private void carregarTabela() {

        DefaultTableModel modelo
                = (DefaultTableModel) tableEntregas.getModel();

        modelo.setRowCount(0);

        List<Entrega> lista
                = entregaDAO.listar();

        for (Entrega entrega
                : lista) {

            modelo.addRow(new Object[]{
                entrega.getId_entrega(),
                "Solicitação #"
                + entrega.getFk_solicitacao(),
                entrega.getData_entrega(),
                entrega.getResponsavel_entrega(),
                entrega.getStatus()
            });
        }
    }

    private void limparCampos() {

        txtDataEntrega.setText("");
        txtResponsavelEntrega.setText("");
        txtObservacao.setText("");

        id_entrega_selecionada = 0;

        tableEntregas.clearSelection();

        DefaultTableModel modelo
                = (DefaultTableModel) tableItens.getModel();

        modelo.setRowCount(0);

        if (cbSolicitacao.getItemCount() > 0) {
            cbSolicitacao.setSelectedIndex(0);
        }

        cbSolicitacao.setEnabled(true);

        if (cbStatus.getItemCount() > 0) {
            cbStatus.setSelectedItem(
                    "REGISTRADA"
            );
        }

        txtDataEntrega.requestFocus();
    }

