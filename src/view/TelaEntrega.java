    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        if (cbSolicitacao.getSelectedItem()
                == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma solicitação."
            );

            return;
        }

        String data_texto
                = txtDataEntrega.getText().trim();

        String responsavel
                = txtResponsavelEntrega
                        .getText()
                        .trim();

        String observacao
                = txtObservacao
                        .getText()
                        .trim();

        if (data_texto.isEmpty()
                || responsavel.isEmpty()
                || observacao.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Preencha todos os campos."
            );

            return;
        }

        try {

            LocalDate data_entrega
                    = LocalDate.parse(
                            data_texto,
                            formato_data
                    );

            int fk_solicitacao
                    = obterIdSolicitacaoSelecionada();

            if (fk_solicitacao == 0) {

                JOptionPane.showMessageDialog(
                        this,
                        "Solicitação inválida."
                );

                return;
            }

            Entrega entrega
                    = new Entrega();

            entrega.setData_entrega(
                    data_entrega
            );

            entrega.setResponsavel_entrega(
                    responsavel
            );

            entrega.setObservacao(
                    observacao
            );

            entrega.setStatus(
                    cbStatus
                            .getSelectedItem()
                            .toString()
            );

            entrega.setFk_solicitacao(
                    fk_solicitacao
            );

            entregaDAO.cadastrar(entrega);

            JOptionPane.showMessageDialog(
                    this,
                    "Entrega cadastrada com sucesso!"
            );

            limparCampos();
            carregarSolicitacoes();
            carregarTabela();

        } catch (DateTimeParseException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Digite a data no formato dd/MM/yyyy."
            );
        }
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void tableEntregasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableEntregasMouseClicked
        int linha
                = tableEntregas.getSelectedRow();

        if (linha < 0) {
            return;
        }

        id_entrega_selecionada
                = Integer.parseInt(
                        tableEntregas
                                .getValueAt(linha, 0)
                                .toString()
                );

        Entrega entrega
                = entregaDAO.buscarPorId(
                        id_entrega_selecionada
                );

        if (entrega == null) {
            return;
        }

        txtDataEntrega.setText(
                entrega.getData_entrega()
                        .format(formato_data)
        );

        txtResponsavelEntrega.setText(
                entrega.getResponsavel_entrega()
        );

        txtObservacao.setText(
                entrega.getObservacao()
        );

        cbStatus.setSelectedItem(
                entrega.getStatus()
        );

        String solicitacao
                = "Solicitação #"
                + entrega.getFk_solicitacao();

        cbSolicitacao.setSelectedItem(
                solicitacao
        );

        cbSolicitacao.setEnabled(false);

        carregarItensDaSolicitacao(
                entrega.getFk_solicitacao()
        );
    }//GEN-LAST:event_tableEntregasMouseClicked

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        if (id_entrega_selecionada == 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma entrega."
            );

            return;
        }

        try {

            LocalDate data_entrega
                    = LocalDate.parse(
                            txtDataEntrega
                                    .getText()
                                    .trim(),
                            formato_data
                    );

            String responsavel
                    = txtResponsavelEntrega
                            .getText()
                            .trim();

            String observacao
                    = txtObservacao
                            .getText()
                            .trim();

            if (responsavel.isEmpty()
                    || observacao.isEmpty()) {

                JOptionPane.showMessageDialog(
                        this,
                        "Preencha todos os campos."
                );

                return;
            }

            Entrega entregaExistente
                    = entregaDAO.buscarPorId(
                            id_entrega_selecionada
                    );

            if (entregaExistente == null) {

                JOptionPane.showMessageDialog(
                        this,
                        "Entrega não encontrada."
                );

                return;
            }

            Entrega entrega
                    = new Entrega();

            entrega.setId_entrega(
                    id_entrega_selecionada
            );

            entrega.setData_entrega(
                    data_entrega
            );

            entrega.setResponsavel_entrega(
                    responsavel
            );

            entrega.setObservacao(
                    observacao
            );

            entrega.setStatus(
                    cbStatus
                            .getSelectedItem()
                            .toString()
            );

            entrega.setFk_solicitacao(
                    entregaExistente.getFk_solicitacao()
            );

            entregaDAO.atualizar(
                    entrega
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Entrega alterada com sucesso!"
            );

            limparCampos();
            carregarSolicitacoes();
            carregarTabela();

        } catch (DateTimeParseException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Data inválida. Use dd/MM/yyyy."
            );
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (id_entrega_selecionada == 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Selecione uma entrega."
            );

            return;
        }

        int resposta
                = JOptionPane.showConfirmDialog(
                        this,
                        "Deseja realmente excluir "
                        + "esta entrega?",
                        "Confirmação",
                        JOptionPane.YES_NO_OPTION
                );

        if (resposta
                == JOptionPane.YES_OPTION) {

            entregaDAO.excluir(
                    id_entrega_selecionada
            );

            JOptionPane.showMessageDialog(
                    this,
                    "Entrega excluída com sucesso!"
            );

            limparCampos();
            carregarSolicitacoes();
            carregarTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

